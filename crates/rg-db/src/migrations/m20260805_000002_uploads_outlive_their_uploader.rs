/// Which rule the producing account's column is to carry.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum Shape {
    /// Nullable, `ON DELETE SET NULL` — the content outlives its author.
    Ghost,
    /// `NOT NULL`, `ON DELETE CASCADE` — the pre-migration rule.
    Owned,
}

impl Shape {
    fn nullability(self) -> &'static str {
        match self {
            Self::Ghost => "NULL",
            Self::Owned => "NOT NULL",
        }
    }

    fn on_delete(self) -> &'static str {
        match self {
            Self::Ghost => "SET NULL",
            Self::Owned => "CASCADE",
        }
    }
}

