/// Rebuild the three tables with the requested rule, on one pinned connection
/// under an explicit write boundary.
///
/// `foreign_keys` and `legacy_alter_table` are connection-local and cannot be
/// changed after a transaction starts. Acquiring the connection first lets us
/// establish and verify those settings, then `BEGIN IMMEDIATE` excludes every
/// other writer for the whole rebuild. SQLite DDL is transactional, so any
/// error restores all three tables, their indexes and their sequences together.
async fn sqlite_rebuild(manager: &SchemaManager<'_>, shape: Shape) -> Result<(), DbErr> {
    sqlite_rebuild_with_hook(manager, shape, |_| async { Ok(()) }).await
}

/// The rebuild, with a hook the tests use to fail it at a chosen point.
async fn sqlite_rebuild_with_hook<F, Fut>(
    manager: &SchemaManager<'_>,
    shape: Shape,
    after_step: F,
) -> Result<(), DbErr>
where
    F: Fn(SqliteRebuildPoint) -> Fut,
    Fut: Future<Output = Result<(), DbErr>>,
{
    let pool = match manager.get_connection() {
        SchemaManagerConnection::Connection(
            db @ DatabaseConnection::SqlxSqlitePoolConnection(_),
        ) => db.get_sqlite_connection_pool(),
        SchemaManagerConnection::Connection(_) => {
            return Err(DbErr::Migration(
                "m20260805_000002: SQLite rebuild received a non-SQLite connection".to_string(),
            ));
        }
        SchemaManagerConnection::Transaction(_) => {
            return Err(DbErr::Migration(
                "m20260805_000002: SQLite rebuild requires a non-transactional migration \
                 connection so its connection-local PRAGMAs can be set before BEGIN"
                    .to_string(),
            ));
        }
    };
    let mut connection = pool
        .acquire()
        .await
        .map_err(|error| sqlite_error("acquire a dedicated connection", error))?;

    let mut sequences = Vec::with_capacity(SQLITE_TABLES.len());
    for table in &SQLITE_TABLES {
        assert_sqlite_columns(&mut connection, table).await?;
        sequences.push(sqlite_autoincrement_seq(&mut connection, table.name).await?);
    }

    if let Err(error) = prepare_sqlite_rebuild_connection(&mut connection).await {
        return finish_sqlite_rebuild(&mut connection, Err(error), false).await;
    }

    if let Err(error) = sqlite_execute(
        &mut connection,
        "begin the write boundary",
        "BEGIN IMMEDIATE",
    )
    .await
    {
        return finish_sqlite_rebuild(&mut connection, Err(error), false).await;
    }

    let work_result = async {
        after_step(SqliteRebuildPoint::WriteBoundary).await?;
        for (table, sequence) in SQLITE_TABLES.iter().zip(sequences) {
            rebuild_one_table(&mut connection, table, shape, sequence).await?;
            after_step(SqliteRebuildPoint::TableRebuilt(table.name)).await?;
        }
        assert_referential_integrity(&mut connection).await?;
        after_step(SqliteRebuildPoint::SchemaRestored).await?;
        sqlite_execute(&mut connection, "commit the rebuilt tables", "COMMIT").await
    }
    .await;

    finish_sqlite_rebuild(&mut connection, work_result, true).await
}

/// Where a test hook can interrupt the rebuild.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum SqliteRebuildPoint {
    WriteBoundary,
    TableRebuilt(&'static str),
    SchemaRestored,
}

async fn rebuild_one_table(
    connection: &mut SqlitePoolConnection,
    table: &SqliteTable,
    shape: Shape,
    sequence: Option<i64>,
) -> Result<(), DbErr> {
    let name = table.name;
    let staging = format!("{name}_pre_ghost_uploader");
    let columns = table
        .columns
        .iter()
        .map(|column| format!("\"{column}\""))
        .collect::<Vec<_>>()
        .join(", ");
    let body = table.body.replace("{rule}", shape.nullability());
    let foreign_keys = table.foreign_keys.replace("{on_delete}", shape.on_delete());

    let drop_indexes = table
        .indexes
        .iter()
        .map(|(index, _)| format!("DROP INDEX IF EXISTS \"{index}\";"))
        .collect::<String>();
    sqlite_execute(
        connection,
        &format!("drop the {name} indexes"),
        &drop_indexes,
    )
    .await?;

    sqlite_execute(
        connection,
        &format!("copy {name} into the replacement table"),
        &format!(
            r#"
            ALTER TABLE "{name}" RENAME TO "{staging}";

            CREATE TABLE "{name}" ({body},{foreign_keys}
            );

            INSERT INTO "{name}" ({columns}) SELECT {columns} FROM "{staging}";

            DROP TABLE "{staging}";
            "#
        ),
    )
    .await?;

    let restore_indexes = table
        .indexes
        .iter()
        .map(|(_, statement)| *statement)
        .collect::<Vec<_>>()
        .join("\n");
    sqlite_execute(
        connection,
        &format!("restore the {name} indexes"),
        &restore_indexes,
    )
    .await?;

    restore_sequence(connection, table, sequence).await
}

/// Put the table's `AUTOINCREMENT` high-water mark back.
///
/// The replacement table's counter starts from the highest id copied in, which
/// is lower than the old one whenever the most recent row was hard-deleted —
/// and a release-asset id is part of its blob key, so a reused id would name an
/// object a previous asset may still own. A direct `sqlite_sequence` UPDATE
/// inside this transaction is overwritten by SQLite's in-memory sequence state
/// at commit, so the mark is advanced through a real, temporary row instead.
async fn restore_sequence(
    connection: &mut SqlitePoolConnection,
    table: &SqliteTable,
    sequence: Option<i64>,
) -> Result<(), DbErr> {
    let Some(sequence) = sequence else {
        return Ok(());
    };
    sqlite_execute(
        connection,
        &format!("restore the {} AUTOINCREMENT high-water mark", table.name),
        &table.sequence_row.replace("{seq}", &sequence.to_string()),
    )
    .await
}

/// Prove, on this database, that the two pragmas the rebuild depends on still do
/// what it needs — before it touches a row.
///
/// `release_assets` carries `REFERENCES "releases"`, so renaming `releases` out
/// of the way must leave that clause pointing at the *name*: the replacement
/// table then inherits it and dropping the old one cascades nothing. Otherwise
/// SQLite rewrites the clause to follow the rename and the `DROP TABLE` that
/// ends the rebuild silently takes every release asset with it.
///
/// Getting that property needs **both** pragmas, which is not what either one's
/// documentation suggests on its own (established by experiment in
/// `m20260730_000001_repositories_namespace_unique`): `foreign_keys = ON`
/// rewrites the clauses whatever `legacy_alter_table` says, and
/// `legacy_alter_table = OFF` rewrites them whatever `foreign_keys` says.
/// `foreign_keys = OFF` is separately what stops `DROP TABLE`'s implicit
/// `DELETE` from firing `ON DELETE CASCADE`.
///
/// Both are also per-connection and no-ops inside a transaction, and SeaORM
/// happens not to wrap SQLite migrations in one — an implementation detail of a
/// dependency, holding up the difference between a migration and a data loss.
/// So rather than trust the combination, exercise it.
async fn prepare_sqlite_rebuild_connection(
    connection: &mut SqlitePoolConnection,
) -> Result<(), DbErr> {
    sqlite_execute(
        connection,
        "disable foreign keys on the rebuild connection",
        "PRAGMA foreign_keys = OFF",
    )
    .await?;
    sqlite_execute(
        connection,
        "enable legacy ALTER TABLE semantics on the rebuild connection",
        "PRAGMA legacy_alter_table = ON",
    )
    .await?;

    let foreign_keys = sqlite_scalar(
        connection,
        "read PRAGMA foreign_keys",
        "PRAGMA foreign_keys",
    )
    .await?
    .unwrap_or(-1);
    let legacy_alter_table = sqlite_scalar(
        connection,
        "read PRAGMA legacy_alter_table",
        "PRAGMA legacy_alter_table",
    )
    .await?
    .unwrap_or(-1);
    if foreign_keys != 0 || legacy_alter_table != 1 {
        return Err(DbErr::Migration(format!(
            "m20260805_000002: refusing to rebuild the upload tables — the dedicated \
             connection reported foreign_keys={foreign_keys} and \
             legacy_alter_table={legacy_alter_table}, expected 0 and 1"
        )));
    }

    assert_foreign_keys_can_be_suspended(connection).await
}

async fn assert_foreign_keys_can_be_suspended(
    connection: &mut SqlitePoolConnection,
) -> Result<(), DbErr> {
    const PARENT: &str = "_forgekeep_ghost_probe_parent";
    const CHILD: &str = "_forgekeep_ghost_probe_child";
    const RENAMED: &str = "_forgekeep_ghost_probe_parent_renamed";

    let probe_result = async {
        sqlite_execute(
            connection,
            "exercise the foreign-key rename probe",
            &format!(
                r#"
                DROP TABLE IF EXISTS "{CHILD}";
                DROP TABLE IF EXISTS "{PARENT}";
                DROP TABLE IF EXISTS "{RENAMED}";
                CREATE TABLE "{PARENT}" ("id" integer NOT NULL PRIMARY KEY);
                CREATE TABLE "{CHILD}" (
                    "id" integer NOT NULL PRIMARY KEY,
                    "pid" integer NULL REFERENCES "{PARENT}" ("id") ON DELETE CASCADE
                );
                ALTER TABLE "{PARENT}" RENAME TO "{RENAMED}";
                "#
            ),
        )
        .await?;

        sqlite_optional_string(
            connection,
            "read the foreign-key rename probe",
            &format!("SELECT sql FROM sqlite_master WHERE type = 'table' AND name = '{CHILD}'"),
        )
        .await
    }
    .await;

    let cleanup_result = sqlite_execute(
        connection,
        "remove the foreign-key rename probe",
        &format!(r#"DROP TABLE IF EXISTS "{CHILD}"; DROP TABLE IF EXISTS "{RENAMED}";"#),
    )
    .await;

    let child_sql = match (probe_result, cleanup_result) {
        (Ok(child_sql), Ok(())) => child_sql,
        (Err(error), Ok(())) => return Err(error),
        (Ok(_), Err(cleanup_error)) => return Err(cleanup_error),
        (Err(error), Err(cleanup_error)) => {
            return Err(combine_sqlite_errors(error, vec![cleanup_error]));
        }
    };

    let followed_the_rename = child_sql.as_deref().is_none_or(|sql| sql.contains(RENAMED));

    if followed_the_rename {
        return Err(DbErr::Migration(format!(
            "m20260805_000002: refusing to rebuild the upload tables — on this connection \
             `PRAGMA foreign_keys = OFF` did not take effect (the probe table's REFERENCES \
             clause followed the rename: {child_sql:?}). Running the rebuild anyway would drop \
             `releases` while foreign keys are enforced, and every asset of every release would \
             be cascaded away."
        )));
    }

    Ok(())
}

/// Fail loudly if the rebuild left a dangling reference behind.
async fn assert_referential_integrity(connection: &mut SqlitePoolConnection) -> Result<(), DbErr> {
    let violations = sqlite_scalar(
        connection,
        "check the rebuilt tables' foreign keys",
        "SELECT count(*) FROM pragma_foreign_key_check",
    )
    .await?
    .unwrap_or(0);

    if violations > 0 {
        return Err(DbErr::Migration(format!(
            "m20260805_000002: the upload-table rebuild left {violations} dangling foreign key \
             reference(s) behind"
        )));
    }

    Ok(())
}

/// Refuse to rebuild a table whose columns are not the ones this migration
/// knows how to copy.
async fn assert_sqlite_columns(
    connection: &mut SqlitePoolConnection,
    table: &SqliteTable,
) -> Result<(), DbErr> {
    let name = table.name;
    let rows = (&mut **connection)
        .fetch_all(format!("SELECT name FROM pragma_table_info('{name}')").as_str())
        .await
        .map_err(|error| sqlite_error(&format!("read the {name} columns"), error))?;

    let mut live = rows
        .iter()
        .map(|row| {
            row.try_get::<String, _>(0)
                .map_err(|error| sqlite_error(&format!("decode a {name} column"), error))
        })
        .collect::<Result<Vec<_>, _>>()?;
    live.sort();

    let mut expected: Vec<String> = table.columns.iter().map(|c| (*c).to_string()).collect();
    expected.sort();

    if live != expected {
        return Err(DbErr::Migration(format!(
            "m20260805_000002: refusing to rebuild `{name}` — its columns are {live:?}, but this \
             migration copies {expected:?}. A column was added to the table without updating \
             SQLITE_TABLES in this migration; rebuilding now would drop it."
        )));
    }

    Ok(())
}

/// The current `AUTOINCREMENT` high-water mark for a table, if any.
async fn sqlite_autoincrement_seq(
    connection: &mut SqlitePoolConnection,
    table: &str,
) -> Result<Option<i64>, DbErr> {
    sqlite_scalar(
        connection,
        &format!("read the {table} AUTOINCREMENT high-water mark"),
        &format!("SELECT seq FROM sqlite_sequence WHERE name = '{table}'"),
    )
    .await
}

type SqlitePoolConnection = sea_orm::sqlx::pool::PoolConnection<Sqlite>;

async fn sqlite_execute(
    connection: &mut SqlitePoolConnection,
    action: &str,
    sql: &str,
) -> Result<(), DbErr> {
    (&mut **connection)
        .execute(sql)
        .await
        .map(|_| ())
        .map_err(|error| sqlite_error(action, error))
}

async fn sqlite_scalar(
    connection: &mut SqlitePoolConnection,
    action: &str,
    sql: &str,
) -> Result<Option<i64>, DbErr> {
    (&mut **connection)
        .fetch_optional(sql)
        .await
        .map_err(|error| sqlite_error(action, error))?
        .map(|row| {
            row.try_get::<i64, _>(0)
                .map_err(|error| sqlite_error(action, error))
        })
        .transpose()
}

async fn sqlite_optional_string(
    connection: &mut SqlitePoolConnection,
    action: &str,
    sql: &str,
) -> Result<Option<String>, DbErr> {
    (&mut **connection)
        .fetch_optional(sql)
        .await
        .map_err(|error| sqlite_error(action, error))?
        .map(|row| {
            row.try_get::<String, _>(0)
                .map_err(|error| sqlite_error(action, error))
        })
        .transpose()
}

async fn finish_sqlite_rebuild(
    connection: &mut SqlitePoolConnection,
    work_result: Result<(), DbErr>,
    transaction_started: bool,
) -> Result<(), DbErr> {
    let mut cleanup_errors = Vec::new();
    if work_result.is_err() && transaction_started {
        if let Err(error) =
            sqlite_execute(connection, "roll back the rebuilt tables", "ROLLBACK").await
        {
            cleanup_errors.push(error);
        }
    }
    if let Err(error) = sqlite_execute(
        connection,
        "disable legacy ALTER TABLE semantics",
        "PRAGMA legacy_alter_table = OFF",
    )
    .await
    {
        cleanup_errors.push(error);
    }
    if let Err(error) = sqlite_execute(
        connection,
        "restore foreign-key enforcement",
        "PRAGMA foreign_keys = ON",
    )
    .await
    {
        cleanup_errors.push(error);
    }

    match (work_result, cleanup_errors.is_empty()) {
        (Ok(()), true) => Ok(()),
        (Ok(()), false) => {
            connection.close_on_drop();
            Err(combine_sqlite_errors(
                DbErr::Migration(
                    "m20260805_000002: SQLite rebuild committed but connection cleanup failed"
                        .to_string(),
                ),
                cleanup_errors,
            ))
        }
        (Err(error), true) => Err(error),
        (Err(error), false) => {
            connection.close_on_drop();
            Err(combine_sqlite_errors(error, cleanup_errors))
        }
    }
}

fn sqlite_error(action: &str, error: sea_orm::sqlx::Error) -> DbErr {
    DbErr::Migration(format!(
        "m20260805_000002: SQLite rebuild failed to {action}: {error}"
    ))
}

fn combine_sqlite_errors(primary: DbErr, cleanup: Vec<DbErr>) -> DbErr {
    let cleanup = cleanup
        .into_iter()
        .map(|error| error.to_string())
        .collect::<Vec<_>>()
        .join("; ");
    DbErr::Migration(format!("{primary}; cleanup also failed: {cleanup}"))
}

