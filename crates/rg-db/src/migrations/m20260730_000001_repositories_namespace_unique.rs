/// The unique index that replaces the account-wide `UNIQUE (owner_id, name)`.
const NAMESPACE_INDEX: &str = "uq_repositories_namespace_name";
/// Non-unique stand-in for the lookups the old unique index also served.
const OWNER_NAME_INDEX: &str = "idx_repositories_owner_id_name";

/// Columns of `repositories` as of this migration, in the order the SQLite
/// rebuild copies them. Checked against the live table before anything is
/// dropped — a rebuild that silently loses a column added by a migration this
/// one has not heard of would be far worse than a refusal to run.
const SQLITE_COLUMNS: [&str; 14] = [
    "id",
    "owner_id",
    "name",
    "description",
    "is_private",
    "default_branch",
    "fork_id",
    "stars_count",
    "forks_count",
    "created_at",
    "updated_at",
    "org_id",
    "deleted_at",
    "origin_repo_id",
];

#[async_trait::async_trait]
impl MigrationTrait for Migration {
    async fn up(&self, manager: &SchemaManager) -> Result<(), DbErr> {
        match manager.get_database_backend() {
            DatabaseBackend::Sqlite => sqlite_rebuild(manager, Shape::NamespaceKey).await,
            DatabaseBackend::Postgres => postgres_up(manager).await,
            DatabaseBackend::MySql => mysql_up(manager).await,
        }
    }

    async fn down(&self, manager: &SchemaManager) -> Result<(), DbErr> {
        match manager.get_database_backend() {
            DatabaseBackend::Sqlite => sqlite_rebuild(manager, Shape::OwnerAccount).await,
            DatabaseBackend::Postgres => postgres_down(manager).await,
            DatabaseBackend::MySql => mysql_down(manager).await,
        }
    }
}

/// Which uniqueness the rebuilt SQLite table is to carry.
///
/// `down` is a real reversal rather than a half-revert: it puts the account-wide
/// constraint back. If repositories that only the new rule allows have been
/// created since, restoring it fails loudly — which is the honest answer, the
/// rows cannot go back.
#[derive(Clone, Copy)]
enum Shape {
    NamespaceKey,
    OwnerAccount,
}

// ── SQLite ──────────────────────────────────────────────────────────────────

/// The generated column, spelled for SQLite (`||` concatenates).
const SQLITE_NAMESPACE_KEY: &str = r#""namespace_key" text GENERATED ALWAYS AS (
        CASE WHEN "deleted_at" IS NOT NULL THEN NULL
             WHEN "org_id" IS NULL THEN 'u' || "owner_id"
             ELSE 'o' || "org_id" END) STORED"#;

/// The three FTS triggers on `repositories`. The rebuild drops and recreates
/// them, so this copy must retain the live-row semantics installed by
/// `m20260804_000006_repo_fts_soft_delete` even when the namespace migration is
/// rolled back later.
const SQLITE_FTS_TRIGGERS: &str = r#"
    CREATE TRIGGER IF NOT EXISTS repos_fts_insert AFTER INSERT ON repositories
    WHEN new.deleted_at IS NULL BEGIN
        INSERT INTO repos_fts(rowid, name, description)
        VALUES (new.id, new.name, COALESCE(new.description, ''));
    END;

    CREATE TRIGGER IF NOT EXISTS repos_fts_delete AFTER DELETE ON repositories BEGIN
        DELETE FROM repos_fts WHERE rowid = old.id;
    END;

    CREATE TRIGGER IF NOT EXISTS repos_fts_update AFTER UPDATE ON repositories BEGIN
        DELETE FROM repos_fts WHERE rowid = old.id;
        INSERT INTO repos_fts(rowid, name, description)
        SELECT new.id, new.name, COALESCE(new.description, '')
        WHERE new.deleted_at IS NULL;
    END;
"#;

/// Rebuild `repositories` with the requested uniqueness.
///
/// SQLite cannot drop a constraint declared inside `CREATE TABLE`, so this is
/// the documented table-rebuild (see the module header for why foreign key
/// enforcement has to be suspended across it).
async fn sqlite_rebuild(manager: &SchemaManager<'_>, shape: Shape) -> Result<(), DbErr> {
    let db = manager.get_connection();

    assert_sqlite_columns(manager).await?;
    assert_foreign_keys_can_be_suspended(manager).await?;
    let sequence = sqlite_autoincrement_seq(manager).await?;

    let (extra_column, table_constraint, extra_index) = match shape {
        Shape::NamespaceKey => (
            format!(",\n        {SQLITE_NAMESPACE_KEY}"),
            String::new(),
            format!(
                r#"CREATE UNIQUE INDEX "{NAMESPACE_INDEX}" ON "repositories" ("namespace_key", "name");"#
            ),
        ),
        Shape::OwnerAccount => (
            String::new(),
            ",\n        UNIQUE (\"owner_id\", \"name\")".to_string(),
            String::new(),
        ),
    };

    let columns = SQLITE_COLUMNS
        .iter()
        .map(|column| format!("\"{column}\""))
        .collect::<Vec<_>>()
        .join(", ");

    let sql = format!(
        r#"
        PRAGMA foreign_keys = OFF;
        PRAGMA legacy_alter_table = ON;

        DROP TRIGGER IF EXISTS repos_fts_insert;
        DROP TRIGGER IF EXISTS repos_fts_delete;
        DROP TRIGGER IF EXISTS repos_fts_update;
        DROP INDEX IF EXISTS "idx_repositories_org_id";
        DROP INDEX IF EXISTS "idx_repositories_origin_repo_id";
        DROP INDEX IF EXISTS "{OWNER_NAME_INDEX}";
        DROP INDEX IF EXISTS "{NAMESPACE_INDEX}";

        ALTER TABLE "repositories" RENAME TO "repositories_pre_namespace_key";

        CREATE TABLE "repositories" (
            "id" integer NOT NULL PRIMARY KEY AUTOINCREMENT,
            "owner_id" bigint NOT NULL,
            "name" varchar NOT NULL,
            "description" text NULL,
            "is_private" boolean NOT NULL DEFAULT FALSE,
            "default_branch" varchar NOT NULL DEFAULT 'main',
            "fork_id" bigint NULL,
            "stars_count" bigint NOT NULL DEFAULT 0,
            "forks_count" bigint NOT NULL DEFAULT 0,
            "created_at" timestamp_with_timezone_text NOT NULL,
            "updated_at" timestamp_with_timezone_text NOT NULL,
            "org_id" bigint NULL,
            "deleted_at" timestamp_with_timezone_text NULL,
            "origin_repo_id" bigint NULL{extra_column}{table_constraint},
            FOREIGN KEY ("owner_id") REFERENCES "users" ("id") ON DELETE CASCADE
        );

        INSERT INTO "repositories" ({columns})
            SELECT {columns} FROM "repositories_pre_namespace_key";

        DROP TABLE "repositories_pre_namespace_key";

        {extra_index}
        CREATE INDEX "{OWNER_NAME_INDEX}" ON "repositories" ("owner_id", "name");
        CREATE INDEX "idx_repositories_org_id" ON "repositories" ("org_id");
        CREATE INDEX "idx_repositories_origin_repo_id" ON "repositories" ("origin_repo_id");

        {SQLITE_FTS_TRIGGERS}

        PRAGMA legacy_alter_table = OFF;
        PRAGMA foreign_keys = ON;
        "#
    );

    db.execute_unprepared(&sql).await?;
    assert_referential_integrity(manager).await?;

    // The new table's AUTOINCREMENT counter starts from the highest id copied
    // in, which is lower than the old one whenever the most recent repository
    // was hard-deleted. Restore it, or the next repository created reuses an id
    // that already appeared in URLs, audit rows and on disk.
    if let Some(seq) = sequence {
        db.execute(Statement::from_sql_and_values(
            DatabaseBackend::Sqlite,
            "INSERT OR REPLACE INTO sqlite_sequence(name, seq) VALUES ('repositories', ?)",
            [seq.into()],
        ))
        .await?;
    }

    Ok(())
}

/// Prove, on this database, that the two pragmas the rebuild depends on still do
/// what it needs — before it touches a row.
///
/// The procedure rests on one property: renaming `repositories` out of the way
/// must leave the 17 incoming `REFERENCES "repositories"` clauses pointing at
/// the *name*, so the new table inherits them and dropping the old one cascades
/// nothing. Otherwise SQLite rewrites those clauses to follow the rename, and
/// the `DROP TABLE` that ends the rebuild silently takes every issue, pull
/// request and star with it.
///
/// Getting that property needs **both** pragmas, which is not what either one's
/// documentation suggests on its own and was established by experiment:
/// `foreign_keys = ON` rewrites the clauses whatever `legacy_alter_table` says,
/// and `legacy_alter_table = OFF` rewrites them whatever `foreign_keys` says.
/// `foreign_keys = OFF` is separately what stops `DROP TABLE`'s implicit
/// `DELETE` from firing `ON DELETE CASCADE`.
///
/// Both are also per-connection and no-ops inside a transaction, and SeaORM
/// happens not to wrap SQLite migrations in one — an implementation detail of a
/// dependency, holding up the difference between a migration and a data loss.
/// So rather than trust the combination, exercise it: rename a throwaway parent
/// and read back whether its child's `REFERENCES` clause followed.
async fn assert_foreign_keys_can_be_suspended(manager: &SchemaManager<'_>) -> Result<(), DbErr> {
    const PARENT: &str = "_forgekeep_fk_probe_parent";
    const CHILD: &str = "_forgekeep_fk_probe_child";
    const RENAMED: &str = "_forgekeep_fk_probe_parent_renamed";

    let db = manager.get_connection();

    db.execute_unprepared(&format!(
        r#"
        DROP TABLE IF EXISTS "{CHILD}";
        DROP TABLE IF EXISTS "{PARENT}";
        DROP TABLE IF EXISTS "{RENAMED}";

        PRAGMA foreign_keys = OFF;
        PRAGMA legacy_alter_table = ON;
        CREATE TABLE "{PARENT}" ("id" integer NOT NULL PRIMARY KEY);
        CREATE TABLE "{CHILD}" (
            "id" integer NOT NULL PRIMARY KEY,
            "pid" integer NULL REFERENCES "{PARENT}" ("id") ON DELETE CASCADE
        );
        ALTER TABLE "{PARENT}" RENAME TO "{RENAMED}";
        PRAGMA legacy_alter_table = OFF;
        PRAGMA foreign_keys = ON;
        "#
    ))
    .await?;

    let child_sql = manager
        .get_connection()
        .query_one(Statement::from_sql_and_values(
            DatabaseBackend::Sqlite,
            "SELECT sql FROM sqlite_master WHERE type = 'table' AND name = ?",
            [CHILD.into()],
        ))
        .await?
        .map(|row| row.try_get::<String>("", "sql"))
        .transpose()?;

    db.execute_unprepared(&format!(
        r#"DROP TABLE IF EXISTS "{CHILD}"; DROP TABLE IF EXISTS "{RENAMED}";"#
    ))
    .await?;

    let followed_the_rename = child_sql.as_deref().is_none_or(|sql| sql.contains(RENAMED));

    if followed_the_rename {
        return Err(DbErr::Migration(format!(
            "m20260730_000001: refusing to rebuild `repositories` — on this connection \
             `PRAGMA foreign_keys = OFF` did not take effect (the probe table's REFERENCES \
             clause followed the rename: {child_sql:?}). Running the rebuild anyway would \
             drop the table while foreign keys are enforced, and every row referencing a \
             repository would be cascaded away."
        )));
    }

    Ok(())
}

/// Fail loudly if the rebuild left a dangling reference behind.
async fn assert_referential_integrity(manager: &SchemaManager<'_>) -> Result<(), DbErr> {
    let row = manager
        .get_connection()
        .query_one(Statement::from_string(
            DatabaseBackend::Sqlite,
            "SELECT count(*) AS violations FROM pragma_foreign_key_check",
        ))
        .await?;

    let violations = match row {
        Some(row) => row.try_get::<i64>("", "violations")?,
        None => 0,
    };

    if violations > 0 {
        return Err(DbErr::Migration(format!(
            "m20260730_000001: the `repositories` rebuild left {violations} dangling foreign \
             key reference(s) behind"
        )));
    }

    Ok(())
}

/// Refuse to rebuild a table whose columns are not the ones this migration
/// knows how to copy.
async fn assert_sqlite_columns(manager: &SchemaManager<'_>) -> Result<(), DbErr> {
    let rows = manager
        .get_connection()
        .query_all(Statement::from_string(
            DatabaseBackend::Sqlite,
            "SELECT name FROM pragma_table_info('repositories')",
        ))
        .await?;

    let mut live: Vec<String> = Vec::with_capacity(rows.len());
    for row in &rows {
        live.push(row.try_get::<String>("", "name")?);
    }
    live.sort();

    let mut expected: Vec<String> = SQLITE_COLUMNS.iter().map(|c| (*c).to_string()).collect();
    // The rebuild is also the `down` path, where the column is already there.
    if live.iter().any(|column| column == "namespace_key") {
        expected.push("namespace_key".to_string());
    }
    expected.sort();

    if live != expected {
        return Err(DbErr::Migration(format!(
            "m20260730_000001: refusing to rebuild `repositories` — its columns are {live:?}, \
             but this migration copies {expected:?}. A column was added to the table without \
             updating SQLITE_COLUMNS in this migration; rebuilding now would drop it."
        )));
    }

    Ok(())
}

