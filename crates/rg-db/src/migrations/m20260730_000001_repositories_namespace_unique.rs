//! `repositories` held one name per **account**, not one per namespace.
//!
//! The table was born with an inline `UNIQUE ("owner_id", "name")`
//! (`m20260424_000002_create_repositories`), and an organization's repository
//! hangs off its owner's user row (`owner_id = org.owner_id`, see
//! `rg_core::repo::service::resolve_owner`). So the *table* could physically
//! hold only one repository called `db` per account — a personal `alice/db` and
//! an `acme/db` owned by alice were a constraint violation, however carefully
//! the queries above it distinguished the two namespaces (card_92019cc97dcd
//! fixed the query side; this is the schema side, card_615e00843297).
//!
//! The replacement is a stored generated column, `namespace_key`, plus
//! `UNIQUE (namespace_key, name)`:
//!
//! * `'o<org_id>'` for an organization's repository, `'u<owner_id>'` for a
//!   personal one — so the key *is* the namespace, and moving a repository
//!   between them moves which slot it occupies.
//! * `NULL` for a soft-deleted row. Every lookup already filters
//!   `deleted_at IS NULL`, so a deleted repository is invisible to the code but
//!   used to keep holding its name hostage in the index. All three backends
//!   treat NULLs in a unique index as distinct, which is exactly the "occupies
//!   no slot" semantics wanted here.
//!
//!   (Reusing a deleted repository's name end-to-end takes one more fix that is
//!   not the schema's: `delete_repo` soft-deletes the row and leaves
//!   `<repo_root>/<owner>/<name>.git` on disk, so the recreate now clears the
//!   database and dies in `gix init --bare` instead — card_9b6fa1a621a0.)
//!
//! A generated column rather than the two obvious alternatives, because it is
//! the only one that ports to all three backends: partial unique indexes
//! (`WHERE org_id IS NULL`) do not exist in MySQL at all, and functional
//! indexes do not exist in MariaDB. It is `STORED` on SQLite and Postgres and
//! `VIRTUAL` on MySQL — see `mysql_up` for why, which is the only place the
//! three schemas are not the same shape.
//!
//! Uniqueness stays enforced by the database, not by the service layer.
//!
//! ## Per-backend notes
//!
//! **SQLite** — the old constraint is *inline in `CREATE TABLE`*, so there is no
//! index to drop; the table has to be rebuilt. Seventeen tables reference
//! `repositories` with `ON DELETE CASCADE`, which makes the rebuild the
//! dangerous part rather than the constraint: it is done under
//! `PRAGMA foreign_keys = OFF` **and** `PRAGMA legacy_alter_table = ON`
//! together, because either one alone still lets SQLite rewrite those
//! `REFERENCES` clauses to follow the rename — after which the closing
//! `DROP TABLE` cascades every issue, pull request and star away. The whole
//! rebuild is one `execute_unprepared` batch so the pragmas and the statements
//! they govern cannot land on different pool connections, and
//! `assert_foreign_keys_can_be_suspended` proves the combination still holds on
//! this database *before* the first destructive statement runs.
//!
//! **Postgres / MySQL** — the constraint is a real index, but an unnamed one:
//! its name was generated by the server (`repositories_owner_id_name_key` /
//! `owner_id`). Both are looked up in the catalogue by their *column set* rather
//! than assumed, so a database created by a different SeaORM or server version
//! is handled too.
//!
//! A plain `(owner_id, name)` index is created on every backend before the
//! unique one is dropped. It preserves the lookup the unique index was
//! incidentally serving (`find_personal_by_owner_and_name`,
//! `list_personal_by_owner`), and on MySQL it is also what lets the old index be
//! dropped at all — the `owner_id` foreign key needs an index to live on.

use sea_orm::{ConnectionTrait, DatabaseBackend, Statement};
use sea_orm_migration::prelude::*;

