// ── Postgres ────────────────────────────────────────────────────────────────

async fn postgres_up(manager: &SchemaManager<'_>) -> Result<(), DbErr> {
    let db = manager.get_connection();

    db.execute_unprepared(&format!(
        r#"CREATE INDEX IF NOT EXISTS "{OWNER_NAME_INDEX}" ON repositories (owner_id, name)"#
    ))
    .await?;

    if let Some(constraint) = postgres_unique_constraint(manager, "name,owner_id").await? {
        db.execute_unprepared(&format!(
            r#"ALTER TABLE repositories DROP CONSTRAINT "{constraint}""#
        ))
        .await?;
    }

    db.execute_unprepared(
        r#"ALTER TABLE repositories ADD COLUMN IF NOT EXISTS namespace_key text
           GENERATED ALWAYS AS (
               CASE WHEN deleted_at IS NOT NULL THEN NULL
                    WHEN org_id IS NULL THEN 'u' || owner_id::text
                    ELSE 'o' || org_id::text END) STORED"#,
    )
    .await?;

    db.execute_unprepared(&format!(
        r#"CREATE UNIQUE INDEX IF NOT EXISTS "{NAMESPACE_INDEX}"
           ON repositories (namespace_key, name)"#
    ))
    .await?;

    Ok(())
}

async fn postgres_down(manager: &SchemaManager<'_>) -> Result<(), DbErr> {
    let db = manager.get_connection();

    db.execute_unprepared(&format!(r#"DROP INDEX IF EXISTS "{NAMESPACE_INDEX}""#))
        .await?;
    db.execute_unprepared("ALTER TABLE repositories DROP COLUMN IF EXISTS namespace_key")
        .await?;
    if postgres_unique_constraint(manager, "name,owner_id")
        .await?
        .is_none()
    {
        db.execute_unprepared("ALTER TABLE repositories ADD UNIQUE (owner_id, name)")
            .await?;
    }
    db.execute_unprepared(&format!(r#"DROP INDEX IF EXISTS "{OWNER_NAME_INDEX}""#))
        .await?;

    Ok(())
}

/// Name of the unique constraint on `repositories` covering exactly `columns`
/// (comma-joined, sorted by column name).
///
/// Looked up rather than assumed: the constraint was declared inline and
/// unnamed, so its name is whatever the server generated.
async fn postgres_unique_constraint(
    manager: &SchemaManager<'_>,
    columns: &str,
) -> Result<Option<String>, DbErr> {
    let row = manager
        .get_connection()
        .query_one(Statement::from_sql_and_values(
            DatabaseBackend::Postgres,
            r#"
            SELECT con.conname AS conname
            FROM pg_constraint con
            JOIN pg_class rel ON rel.oid = con.conrelid
            JOIN pg_namespace ns ON ns.oid = rel.relnamespace
            WHERE rel.relname = 'repositories'
              AND ns.nspname = current_schema()
              AND con.contype = 'u'
              AND (
                SELECT string_agg(att.attname::text, ',' ORDER BY att.attname)
                FROM unnest(con.conkey) AS k(attnum)
                JOIN pg_attribute att
                  ON att.attrelid = con.conrelid AND att.attnum = k.attnum
              ) = $1
            LIMIT 1
            "#,
            [columns.into()],
        ))
        .await?;

    match row {
        Some(row) => Ok(Some(row.try_get::<String>("", "conname")?)),
        None => Ok(None),
    }
}

// ── MySQL ───────────────────────────────────────────────────────────────────

async fn mysql_up(manager: &SchemaManager<'_>) -> Result<(), DbErr> {
    let db = manager.get_connection();

    // Before the unique index goes: the `owner_id` foreign key needs an index
    // to live on, and MySQL refuses to drop the last one that covers it.
    if mysql_index(manager, "name,owner_id", OWNER_NAME_INDEX)
        .await?
        .is_none()
    {
        db.execute_unprepared(&format!(
            "CREATE INDEX `{OWNER_NAME_INDEX}` ON repositories (owner_id, name)"
        ))
        .await?;
    }

    if let Some(index) = mysql_unique_index(manager, "name,owner_id").await? {
        db.execute_unprepared(&format!("ALTER TABLE repositories DROP INDEX `{index}`"))
            .await?;
    }

    if mysql_column_exists(manager, "namespace_key").await? {
        return Ok(());
    }

    // VIRTUAL, not STORED — the one place the three backends genuinely differ.
    // MySQL refuses a *stored* generated column whose base column carries a
    // foreign key with `ON DELETE CASCADE`, and `owner_id` is exactly that
    // (`repositories_ibfk_1 → users(id) ON DELETE CASCADE`); the attempt comes
    // back as a bare `1215 Cannot add foreign key constraint`. The restriction
    // does not apply to virtual columns, and a secondary index over one is
    // materialized, so uniqueness is enforced by the index just the same.
    db.execute_unprepared(
        "ALTER TABLE repositories ADD COLUMN namespace_key VARCHAR(32)
         GENERATED ALWAYS AS (
             CASE WHEN deleted_at IS NOT NULL THEN NULL
                  WHEN org_id IS NULL THEN CONCAT('u', owner_id)
                  ELSE CONCAT('o', org_id) END) VIRTUAL",
    )
    .await?;

    db.execute_unprepared(&format!(
        "CREATE UNIQUE INDEX `{NAMESPACE_INDEX}` ON repositories (namespace_key, name)"
    ))
    .await?;

    Ok(())
}

async fn mysql_down(manager: &SchemaManager<'_>) -> Result<(), DbErr> {
    let db = manager.get_connection();

    if mysql_index(manager, "name,namespace_key", NAMESPACE_INDEX)
        .await?
        .is_some()
    {
        db.execute_unprepared(&format!(
            "ALTER TABLE repositories DROP INDEX `{NAMESPACE_INDEX}`"
        ))
        .await?;
    }
    if mysql_column_exists(manager, "namespace_key").await? {
        db.execute_unprepared("ALTER TABLE repositories DROP COLUMN namespace_key")
            .await?;
    }
    if mysql_unique_index(manager, "name,owner_id")
        .await?
        .is_none()
    {
        db.execute_unprepared("ALTER TABLE repositories ADD UNIQUE (owner_id, name)")
            .await?;
    }
    if let Some(index) = mysql_index(manager, "name,owner_id", OWNER_NAME_INDEX).await? {
        db.execute_unprepared(&format!("ALTER TABLE repositories DROP INDEX `{index}`"))
            .await?;
    }

    Ok(())
}

/// Name of the *unique* index on `repositories` whose columns are exactly
/// `columns` (comma-joined, sorted by column name).
async fn mysql_unique_index(
    manager: &SchemaManager<'_>,
    columns: &str,
) -> Result<Option<String>, DbErr> {
    mysql_index_matching(manager, columns, "AND s.NON_UNIQUE = 0", None).await
}

/// Same lookup, restricted to one index name — used to make the `CREATE INDEX`
/// calls idempotent (MySQL has no `CREATE INDEX IF NOT EXISTS`).
async fn mysql_index(
    manager: &SchemaManager<'_>,
    columns: &str,
    name: &str,
) -> Result<Option<String>, DbErr> {
    mysql_index_matching(manager, columns, "", Some(name)).await
}

async fn mysql_index_matching(
    manager: &SchemaManager<'_>,
    columns: &str,
    uniqueness: &str,
    name: Option<&str>,
) -> Result<Option<String>, DbErr> {
    let by_name = match name {
        Some(_) => "AND s.INDEX_NAME = ?",
        None => "",
    };
    let sql = format!(
        "SELECT s.INDEX_NAME AS idx
         FROM information_schema.STATISTICS s
         WHERE s.TABLE_SCHEMA = DATABASE()
           AND s.TABLE_NAME = 'repositories'
           {uniqueness}
           {by_name}
         GROUP BY s.INDEX_NAME
         HAVING GROUP_CONCAT(s.COLUMN_NAME ORDER BY s.COLUMN_NAME) = ?
         LIMIT 1"
    );

    let values: Vec<sea_orm::Value> = match name {
        Some(name) => vec![name.into(), columns.into()],
        None => vec![columns.into()],
    };

    let row = manager
        .get_connection()
        .query_one(Statement::from_sql_and_values(
            DatabaseBackend::MySql,
            &sql,
            values,
        ))
        .await?;

    match row {
        Some(row) => Ok(Some(row.try_get::<String>("", "idx")?)),
        None => Ok(None),
    }
}

async fn mysql_column_exists(manager: &SchemaManager<'_>, column: &str) -> Result<bool, DbErr> {
    let row = manager
        .get_connection()
        .query_one(Statement::from_sql_and_values(
            DatabaseBackend::MySql,
            "SELECT COLUMN_NAME AS col
             FROM information_schema.COLUMNS
             WHERE TABLE_SCHEMA = DATABASE()
               AND TABLE_NAME = 'repositories'
               AND COLUMN_NAME = ?",
            [column.into()],
        ))
        .await?;

    Ok(row.is_some())
}
